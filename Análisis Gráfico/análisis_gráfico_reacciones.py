def panel_densidades(df, titulo, archivo, props, ncols=4, log=False):
    props = [p for p in props if df.loc[df['propiedad'] == p, 'valor'].notna().sum() >= 5]
    if not props:
        return
    nfilas = int(np.ceil(len(props) / ncols))
