def top_correlaciones(matriz, n=20):
    m = matriz.where(np.triu(np.ones(matriz.shape), k=1).astype(bool)).stack().dropna()
    # solo pares del MISMO rol: entre roles distintos los compuestos no se relacionan
    mismo = [a.split(' · ')[1] == b.split(' · ')[1] for a, b in m.index]
    m = m[mismo]
    return m.sort_values(key=abs, ascending=False).head(n)

