SUP = {'⁻': '-', '⁺': '+', '⁰': '0', '¹': '1', '²': '2', '³': '3',
       '⁴': '4', '⁵': '5', '⁶': '6', '⁷': '7', '⁸': '8', '⁹': '9'}
NULOS = {'', '/', '-', '--', '---', 'na', 'n/a', 'nd', 'n/d', 'none', 'nan', '?', '.', 's/d'}

def _potencias(texto):
    def rep(m):
        return '^' + ''.join(SUP.get(c, c) for c in m.group(0))
    return re.sub(r'[⁻⁺⁰¹²³⁴⁵⁶⁷⁸⁹]+', rep, texto)

def _a_float(t):
    t = t.strip().replace(' ', '')
    if ',' in t and '.' in t:
        if t.rfind(',') > t.rfind('.'):
            t = t.replace('.', '').replace(',', '.')
        else:
            t = t.replace(',', '')
    elif ',' in t:
        t = t.replace(',', '.')
    t = t.rstrip('.')
    try:
        return float(t)
    except ValueError:
        return np.nan

def to_num(x):
    '''Convierte una celda sucia de Excel en float (o NaN).'''
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return np.nan
    if isinstance(x, (datetime.datetime, datetime.date, pd.Timestamp)):
        return np.nan                      # Excel convirtio "11-1" en fecha
    if isinstance(x, (int, float, np.integer, np.floating)):
        v = float(x)
        return v if np.isfinite(v) else np.nan
    s = str(x).replace('−', '-').replace('–', '-').replace('—', '-').replace('×', 'x')
    s = s.replace('¯', '⁻').replace('\xa0', ' ')
    s = _potencias(s).strip()
    s = re.sub(r'g/cm\S*', '', s)                    # '0,6405 g/cm132' -> '0,6405'
    s = re.sub(r'\(.*?\)', ' ', s).strip()
    s = re.sub(r'^-{2,}', '-', s)                    # '--182,6' -> '-182,6'
    s = re.sub(r'[~≈<>]', '', s).replace('·', 'x').replace('*', 'x').strip()
    if s.lower() in NULOS:
        return np.nan
    m = re.search(r'^(-?[\d.,]+)\s*(?:a|hasta|to|-)\s*(-?[\d.,]+)$', s, flags=re.IGNORECASE)
    if m:
        a, b = _a_float(m.group(1)), _a_float(m.group(2))
        if np.isfinite(a) and np.isfinite(b):
            return (a + b) / 2
    if '±' in s:
        s = s.split('±')[0]
    m = re.search(r'(-?\d[\d.,]*)\s*x\s*10\s*\^?\s*(-?\d+)', s, flags=re.IGNORECASE)
    if m:
        base, expo = _a_float(m.group(1)), _a_float(m.group(2))
        if np.isfinite(base) and np.isfinite(expo):
            return base * (10 ** int(expo))
    return _a_float(s)

